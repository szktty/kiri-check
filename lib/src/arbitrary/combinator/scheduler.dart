import 'dart:async';
import 'dart:collection';

import 'package:collection/collection.dart';
import 'package:kiri_check/src/property/property_internal.dart';
import 'package:stack_trace/stack_trace.dart';

abstract class SchedulerArbitraries {
  static Arbitrary<Scheduler> scheduler({
    int? maxSteps,
    bool microtasks = true,
  }) =>
      SchedulerArbitrary(
        maxSteps: maxSteps ?? defaultMaxSteps,
        microtasks: microtasks,
      );

  static const defaultMaxSteps = 100000;
}

final class SchedulerArbitrary extends ArbitraryBase<Scheduler> {
  SchedulerArbitrary({required this.maxSteps, this.microtasks = true}) {
    _checkMaxSteps(maxSteps);
  }

  final int maxSteps;
  final bool microtasks;

  @override
  int get enumerableCount => 0;

  @override
  List<Scheduler>? get edgeCases => null;

  @override
  bool get isExhaustive => false;

  // The first example runs the tasks in the order Dart itself does.
  @override
  Scheduler getFirst(RandomContext random) => SchedulerImpl(
        maxSteps: maxSteps,
        microtasks: microtasks,
        choices: const [],
      );

  @override
  Scheduler generate(RandomContext random) => generateRandom(random);

  @override
  Scheduler generateRandom(RandomContext random) => SchedulerImpl(
        maxSteps: maxSteps,
        microtasks: microtasks,
        choices: const [],
        // RandomXorshift accepts a seed between 1 and 0x7FFFFFFF.
        seed: random.nextInt(0x7FFFFFFF) + 1,
      );

  @override
  ShrinkingDistance calculateDistance(Scheduler value) =>
      ShrinkingDistance((value as SchedulerImpl).trace.sum);

  // Shrinks the choices of the last run towards the order Dart itself uses.
  // A shrunk scheduler picks the oldest task where its choices run out.
  @override
  List<Scheduler> shrink(Scheduler value, ShrinkingDistance distance) {
    final trace = _trimmed((value as SchedulerImpl).trace);
    if (trace.isEmpty) {
      return [];
    }

    final candidates = <List<int>>[];
    void add(List<int> choices) {
      final trimmed = _trimmed(choices);
      if (!candidates
          .any((c) => const ListEquality<int>().equals(c, trimmed))) {
        candidates.add(trimmed);
      }
    }

    // Drop the choices after a point.
    for (final length in ArbitraryUtils.shrinkLength(
      trace.length,
      minLength: 0,
      granularity: distance.granularity,
    )) {
      add(trace.sublist(0, length));
    }

    // Pick the oldest task at one point.
    for (var i = 0; i < trace.length; i++) {
      if (trace[i] != 0) {
        add(List.of(trace)..[i] = 0);
      }
    }

    // Pick a task closer to the oldest at one point.
    for (var i = 0; i < trace.length; i++) {
      if (trace[i] > 1) {
        add(List.of(trace)..[i] = trace[i] ~/ 2);
      }
    }

    candidates.removeWhere((c) => const ListEquality<int>().equals(c, trace));
    return candidates
        .map(
          (c) => SchedulerImpl(
            maxSteps: maxSteps,
            microtasks: microtasks,
            choices: c,
          ),
        )
        .toList();
  }

  @override
  String describeExample(Scheduler example) => example.toString();

  static List<int> _trimmed(List<int> choices) {
    var length = choices.length;
    while (length > 0 && choices[length - 1] == 0) {
      length--;
    }
    return choices.sublist(0, length);
  }
}

void _checkMaxSteps(int maxSteps) {
  if (maxSteps < 1) {
    throw ArgumentError.value(maxSteps, 'maxSteps', 'must be positive');
  }
}

/// An object generated by `scheduler()` that runs asynchronous code
/// in an order of its own.
///
/// Dart runs asynchronous code on a single thread, and code running
/// concurrently interleaves only where it waits for a future.
/// A scheduler runs the microtasks created by the code, such as the
/// continuations after `await`, in an order chosen by kiri-check instead
/// of the order Dart itself uses, to find interleavings that break the code.
/// When a property fails, the order is shrunk towards the order Dart uses.
abstract class Scheduler {
  Scheduler();

  /// Creates a scheduler that makes the given choices, such as the ones
  /// shown in a falsifying example, to reproduce an interleaving in a test.
  ///
  /// Each choice is the index of the task to run next among the ready ones,
  /// where `0` is the oldest one. The oldest task runs where the choices
  /// run out. `maxSteps` and `microtasks` are the same as of `scheduler()`.
  factory Scheduler.withChoices(
    List<int> choices, {
    int? maxSteps,
    bool microtasks = true,
  }) {
    final maxSteps0 = maxSteps ?? SchedulerArbitraries.defaultMaxSteps;
    _checkMaxSteps(maxSteps0);
    for (final choice in choices) {
      RangeError.checkNotNegative(choice, 'choices');
    }
    return SchedulerImpl(
      maxSteps: maxSteps0,
      microtasks: microtasks,
      choices: List.unmodifiable(choices),
    );
  }

  /// Runs [body] and returns its result.
  ///
  /// Each time two or more microtasks created by [body] are ready to run,
  /// the scheduler chooses which one runs next, unless the scheduler is
  /// created with `microtasks: false`. When no microtask is ready,
  /// the scheduler completes one of the futures passed to [schedule].
  /// Timers created by [body] run on virtual time: when nothing else is
  /// ready, the timer due first runs at once, in the order the timers were
  /// created if they are due at the same time.
  ///
  /// The returned future completes after [body] has completed and the
  /// microtasks left by it have run. Timers left by [body] are cancelled,
  /// and futures returned by [schedule] and not completed yet never
  /// complete. An error not handled by [body], such as one thrown by
  /// a microtask [body] did not wait for, completes the returned future
  /// with the error.
  ///
  /// Each call follows the same schedule from the beginning.
  /// Code outside of Dart, such as I/O, is not controlled by the scheduler.
  Future<T> run<T>(FutureOr<T> Function() body);

  /// Returns a future that completes with the result of [future] when
  /// the scheduler chooses to complete it.
  ///
  /// Use this to reorder the completion of operations, such as calls to
  /// a mocked server, without reordering every microtask. The scheduler
  /// completes one of the scheduled futures at a time, when no microtask
  /// is ready, and waits for [future] to complete before completing
  /// another one. [label] is shown in a falsifying example.
  ///
  /// This can be called only in [run].
  Future<T> schedule<T>(Future<T> future, {String? label});

  /// The virtual time elapsed in the current or last run.
  Duration get elapsed;
}

final class SchedulerImpl extends Scheduler {
  SchedulerImpl({
    required this.maxSteps,
    required this.choices,
    this.microtasks = true,
    this.seed,
  });

  final int maxSteps;

  // Whether the order of the microtasks is chosen.
  final bool microtasks;

  // The choices to make. Where they run out, a random task is chosen if
  // [seed] is given, otherwise the oldest one.
  final List<int> choices;
  final int? seed;

  // The choices made in the current or last run.
  List<int> get trace => List.unmodifiable(_trace);
  final List<int> _trace = [];

  int get steps => _steps;
  int _steps = 0;

  @override
  Duration get elapsed => _now;
  Duration _now = Duration.zero;

  bool _running = false;
  final Queue<_Microtask> _microtasks = Queue();
  final List<_VirtualTimer> _timers = [];
  int _timerSequence = 0;
  final List<_Scheduled<dynamic>> _scheduled = [];
  _Scheduled<dynamic>? _completing;
  Completer<void>? _wake;
  RandomXorshift? _random;
  _Failure? _uncaught;

  // For describing the run.
  int _taskSequence = 0;
  int? _currentTask;
  bool _binding = false;
  final Map<int, StackTrace> _taskLocations = {};
  final List<_Deviation> _deviations = [];

  @override
  Future<T> run<T>(FutureOr<T> Function() body) async {
    if (_running) {
      throw StateError('The scheduler is already running');
    }
    _running = true;
    _trace.clear();
    _steps = 0;
    _now = Duration.zero;
    _microtasks.clear();
    _timers.clear();
    _scheduled.clear();
    _completing = null;
    _uncaught = null;
    _random = seed != null ? RandomXorshift(seed) : null;
    _taskSequence = 0;
    _currentTask = null;
    _taskLocations.clear();
    _deviations.clear();

    final zone = Zone.current.fork(
      specification: ZoneSpecification(
        scheduleMicrotask: _scheduleMicrotask,
        createTimer: _createTimer,
        createPeriodicTimer: _createPeriodicTimer,
        handleUncaughtError: _handleUncaughtError,
        registerCallback: _registerCallback,
        registerUnaryCallback: _registerUnaryCallback,
      ),
    );

    // An error does not leave the zone through a future, so the result
    // is carried as a value.
    Object? result;
    var completed = false;
    unawaited(
      zone.run(() async {
        try {
          return _Success(await body());
          // Any error of the body is passed to the caller.
          // ignore: avoid_catches_without_on_clauses
        } catch (e, s) {
          return _Failure(e, s);
        }
      }).then((value) {
        result = value;
        completed = true;
        _wakeUp();
      }),
    );

    try {
      while (_uncaught == null) {
        if (_microtasks.isNotEmpty) {
          _runMicrotask();
        } else if (completed) {
          break;
        } else if (_completing == null && _scheduled.isNotEmpty) {
          _completeScheduled();
        } else if (_timers.isNotEmpty) {
          _runTimer();
        } else {
          // Waits for code outside of the zone, such as I/O.
          _wake = Completer();
          await _wake!.future;
          _wake = null;
        }
      }
    } finally {
      for (final timer in _timers) {
        timer._active = false;
      }
      _timers.clear();
      _microtasks.clear();
      _scheduled.clear();
      _completing = null;
      _currentTask = null;
      _running = false;
    }

    final uncaught = _uncaught;
    if (uncaught != null) {
      Error.throwWithStackTrace(uncaught.error, uncaught.stackTrace);
    }
    final value = result;
    if (value is _Failure) {
      Error.throwWithStackTrace(value.error, value.stackTrace);
    }
    return (value! as _Success).value as T;
  }

  @override
  Future<T> schedule<T>(Future<T> future, {String? label}) {
    if (!_running) {
      throw StateError('schedule() can be called only in run()');
    }
    final scheduled = _Scheduled<T>(future, label, StackTrace.current);
    _scheduled.add(scheduled);
    _wakeUp();
    return scheduled.completer.future;
  }

  void _step() {
    _steps++;
    if (_steps > maxSteps) {
      throw StateError(
        'The scheduler ran more than $maxSteps tasks; '
        'the code may not terminate',
      );
    }
  }

  int _choose(int length) {
    if (length < 2) {
      return 0;
    }
    final position = _trace.length;
    var index = 0;
    if (position < choices.length) {
      index = choices[position] % length;
    } else if (_random != null) {
      index = _random!.nextInt(length);
    }
    _trace.add(index);
    return index;
  }

  void _runMicrotask() {
    _step();
    final index = microtasks ? _choose(_microtasks.length) : 0;

    _Microtask task;
    if (index == 0) {
      task = _microtasks.removeFirst();
    } else {
      final tasks = _microtasks.toList();
      task = tasks.removeAt(index);
      _deviations.add(_Deviation(_steps, task, tasks.first));
      _microtasks
        ..clear()
        ..addAll(tasks);
    }

    _currentTask = task.id;
    try {
      task.callback();
    } finally {
      _currentTask = null;
    }
  }

  void _completeScheduled() {
    _step();
    final index = _choose(_scheduled.length);
    final scheduled = _scheduled.removeAt(index);
    if (index != 0) {
      _deviations.add(_Deviation(_steps, scheduled, _scheduled.first));
    }
    _completing = scheduled;
    scheduled.release(() {
      if (identical(_completing, scheduled)) {
        _completing = null;
      }
      _wakeUp();
    });
  }

  void _runTimer() {
    _step();
    var next = _timers.first;
    for (final timer in _timers) {
      if (timer._due < next._due ||
          (timer._due == next._due && timer._sequence < next._sequence)) {
        next = timer;
      }
    }
    if (_now < next._due) {
      _now = next._due;
    }
    if (next._periodic) {
      next
        .._due = _now + next._duration
        .._sequence = _timerSequence++;
    } else {
      _timers.remove(next);
      next._active = false;
    }
    next._tick++;
    next._callback(next);
  }

  void _wakeUp() {
    final wake = _wake;
    if (wake != null && !wake.isCompleted) {
      wake.complete();
    }
  }

  // Binds a callback without recording where it is registered.
  T _bind<T>(T Function() bind) {
    _binding = true;
    try {
      return bind();
    } finally {
      _binding = false;
    }
  }

  void _scheduleMicrotask(
    Zone self,
    ZoneDelegate parent,
    Zone zone,
    void Function() f,
  ) {
    if (!_running) {
      parent.scheduleMicrotask(zone, f);
      return;
    }
    final callback = _bind(() => zone.bindCallbackGuarded(f));
    _microtasks.add(_Microtask(_taskSequence++, callback));
    _wakeUp();
  }

  Timer _createTimer(
    Zone self,
    ZoneDelegate parent,
    Zone zone,
    Duration duration,
    void Function() f,
  ) {
    if (!_running) {
      return parent.createTimer(zone, duration, f);
    }
    final callback = _bind(() => zone.bindCallbackGuarded(f));
    return _addTimer(duration, (_) => callback(), periodic: false);
  }

  Timer _createPeriodicTimer(
    Zone self,
    ZoneDelegate parent,
    Zone zone,
    Duration period,
    void Function(Timer) f,
  ) {
    if (!_running) {
      return parent.createPeriodicTimer(zone, period, f);
    }
    final callback = _bind(() => zone.bindUnaryCallbackGuarded(f));
    return _addTimer(period, callback, periodic: true);
  }

  _VirtualTimer _addTimer(
    Duration duration,
    void Function(Timer) callback, {
    required bool periodic,
  }) {
    final positive = duration.isNegative ? Duration.zero : duration;
    final timer = _VirtualTimer(
      this,
      positive,
      _now + positive,
      _timerSequence++,
      callback,
      periodic: periodic,
    );
    _timers.add(timer);
    _wakeUp();
    return timer;
  }

  // Records where the callbacks running in a microtask were registered,
  // such as at `await`, to describe the microtask.
  ZoneCallback<R> _registerCallback<R>(
    Zone self,
    ZoneDelegate parent,
    Zone zone,
    R Function() f,
  ) {
    if (!_running || _binding) {
      return parent.registerCallback(zone, f);
    }
    final location = StackTrace.current;
    return parent.registerCallback(zone, () {
      _noteLocation(location);
      return f();
    });
  }

  ZoneUnaryCallback<R, T> _registerUnaryCallback<R, T>(
    Zone self,
    ZoneDelegate parent,
    Zone zone,
    R Function(T) f,
  ) {
    if (!_running || _binding) {
      return parent.registerUnaryCallback(zone, f);
    }
    final location = StackTrace.current;
    return parent.registerUnaryCallback(zone, (arg) {
      _noteLocation(location);
      return f(arg);
    });
  }

  void _noteLocation(StackTrace location) {
    final task = _currentTask;
    if (_running && task != null) {
      _taskLocations.putIfAbsent(task, () => location);
    }
  }

  void _handleUncaughtError(
    Zone self,
    ZoneDelegate parent,
    Zone zone,
    Object error,
    StackTrace stackTrace,
  ) {
    if (!_running) {
      parent.handleUncaughtError(zone, error, stackTrace);
      return;
    }
    _uncaught ??= _Failure(error, stackTrace);
  }

  String _describeTask(Object task) {
    if (task is _Scheduled<dynamic>) {
      final location = _describeLocation(task.location);
      final label = task.label != null ? "'${task.label}'" : 'a future';
      return location != null
          ? 'scheduled $label at $location'
          : 'scheduled $label';
    }
    final id = (task as _Microtask).id;
    final location = _taskLocations[id];
    final described = location != null ? _describeLocation(location) : null;
    return described != null
        ? 'microtask waiting at $described'
        : 'microtask #$id';
  }

  // Describes the first frame of the code under test.
  static String? _describeLocation(StackTrace stackTrace) {
    final frame = Trace.from(stackTrace).frames.firstWhereOrNull(
          (frame) =>
              !frame.isCore &&
              frame.package != 'kiri_check' &&
              frame.package != 'stack_trace',
        );
    return frame != null ? '${frame.member} (${frame.location})' : null;
  }

  static const _maxDescribedDeviations = 10;

  @override
  // Equal schedulers make the same choices. The state of a run is not
  // compared, so that the shrinker can tell the same candidates.
  // ignore: avoid_equals_and_hash_code_on_mutable_classes
  bool operator ==(Object other) =>
      other is SchedulerImpl &&
      seed == other.seed &&
      maxSteps == other.maxSteps &&
      microtasks == other.microtasks &&
      const ListEquality<int>().equals(choices, other.choices);

  @override
  // Hashes what == compares.
  // ignore: avoid_equals_and_hash_code_on_mutable_classes
  int get hashCode => Object.hash(
        seed,
        maxSteps,
        microtasks,
        const ListEquality<int>().hash(choices),
      );

  @override
  String toString() {
    if (_steps == 0) {
      return seed != null
          ? 'Scheduler(seed: $seed)'
          : 'Scheduler(choices: $choices)';
    }
    final buffer = StringBuffer(
      'Scheduler(choices: ${SchedulerArbitrary._trimmed(_trace)}, '
      'steps: $_steps)',
    );
    for (final deviation in _deviations.take(_maxDescribedDeviations)) {
      buffer
        ..write('\n  step ${deviation.step}: ran ')
        ..write(_describeTask(deviation.chosen))
        ..write('\n    before ')
        ..write(_describeTask(deviation.skipped));
    }
    if (_deviations.length > _maxDescribedDeviations) {
      buffer.write(
        '\n  and ${_deviations.length - _maxDescribedDeviations} '
        'more reorderings',
      );
    }
    return buffer.toString();
  }
}

final class _Microtask {
  const _Microtask(this.id, this.callback);

  final int id;
  final void Function() callback;
}

final class _Scheduled<T> {
  // Listens to the future at once, so that its error is not unhandled
  // until the scheduler completes the scheduled future.
  _Scheduled(Future<T> future, this.label, this.location) {
    unawaited(
      future.then(
        (value) {
          _result = _Success(value);
          _completeIfReleased();
        },
        onError: (Object error, StackTrace stackTrace) {
          _result = _Failure(error, stackTrace);
          _completeIfReleased();
        },
      ),
    );
  }

  final String? label;
  final StackTrace location;
  final Completer<T> completer = Completer();
  Object? _result;
  void Function()? _onComplete;

  // Completes the scheduled future after the original one completes.
  void release(void Function() onComplete) {
    _onComplete = onComplete;
    _completeIfReleased();
  }

  void _completeIfReleased() {
    final result = _result;
    final onComplete = _onComplete;
    if (result == null || onComplete == null || completer.isCompleted) {
      return;
    }
    if (result is _Failure) {
      completer.completeError(result.error, result.stackTrace);
    } else {
      completer.complete((result as _Success).value as T);
    }
    onComplete();
  }
}

// A task run before the oldest ready one.
final class _Deviation {
  const _Deviation(this.step, this.chosen, this.skipped);

  final int step;
  final Object chosen;
  final Object skipped;
}

final class _VirtualTimer implements Timer {
  _VirtualTimer(
    this._scheduler,
    this._duration,
    this._due,
    this._sequence,
    this._callback, {
    required bool periodic,
  }) : _periodic = periodic;

  final SchedulerImpl _scheduler;
  final Duration _duration;
  final void Function(Timer) _callback;
  final bool _periodic;
  Duration _due;
  int _sequence;
  int _tick = 0;
  bool _active = true;

  @override
  bool get isActive => _active;

  @override
  int get tick => _tick;

  @override
  void cancel() {
    _active = false;
    _scheduler._timers.remove(this);
  }
}

final class _Success {
  const _Success(this.value);

  final Object? value;
}

final class _Failure {
  const _Failure(this.error, this.stackTrace);

  final Object error;
  final StackTrace stackTrace;
}
