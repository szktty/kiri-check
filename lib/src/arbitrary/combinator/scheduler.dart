import 'dart:async';
import 'dart:collection';

import 'package:collection/collection.dart';
import 'package:kiri_check/src/property/property_internal.dart';

abstract class SchedulerArbitraries {
  static Arbitrary<Scheduler> scheduler({int? maxSteps}) =>
      SchedulerArbitrary(maxSteps: maxSteps ?? defaultMaxSteps);

  static const defaultMaxSteps = 100000;
}

final class SchedulerArbitrary extends ArbitraryBase<Scheduler> {
  SchedulerArbitrary({required this.maxSteps}) {
    if (maxSteps < 1) {
      throw ArgumentError.value(maxSteps, 'maxSteps', 'must be positive');
    }
  }

  final int maxSteps;

  @override
  int get enumerableCount => 0;

  @override
  List<Scheduler>? get edgeCases => null;

  @override
  bool get isExhaustive => false;

  // The first example runs the tasks in the order Dart itself does.
  @override
  Scheduler getFirst(RandomContext random) =>
      SchedulerImpl(maxSteps: maxSteps, choices: const []);

  @override
  Scheduler generate(RandomContext random) => generateRandom(random);

  @override
  Scheduler generateRandom(RandomContext random) => SchedulerImpl(
        maxSteps: maxSteps,
        choices: const [],
        // RandomXorshift accepts a seed between 1 and 0x7FFFFFFF.
        seed: random.nextInt(0x7FFFFFFF) + 1,
      );

  @override
  ShrinkingDistance calculateDistance(Scheduler value) =>
      ShrinkingDistance((value as SchedulerImpl).trace.sum);

  // Shrinks the choices of the last run towards the order Dart itself uses.
  // A shrunk scheduler picks the oldest task where its choices run out.
  @override
  List<Scheduler> shrink(Scheduler value, ShrinkingDistance distance) {
    final trace = _trimmed((value as SchedulerImpl).trace);
    if (trace.isEmpty) {
      return [];
    }

    final candidates = <List<int>>[];
    void add(List<int> choices) {
      final trimmed = _trimmed(choices);
      if (!candidates
          .any((c) => const ListEquality<int>().equals(c, trimmed))) {
        candidates.add(trimmed);
      }
    }

    // Drop the choices after a point.
    for (final length in ArbitraryUtils.shrinkLength(
      trace.length,
      minLength: 0,
      granularity: distance.granularity,
    )) {
      add(trace.sublist(0, length));
    }

    // Pick the oldest task at one point.
    for (var i = 0; i < trace.length; i++) {
      if (trace[i] != 0) {
        add(List.of(trace)..[i] = 0);
      }
    }

    // Pick a task closer to the oldest at one point.
    for (var i = 0; i < trace.length; i++) {
      if (trace[i] > 1) {
        add(List.of(trace)..[i] = trace[i] ~/ 2);
      }
    }

    candidates.removeWhere((c) => const ListEquality<int>().equals(c, trace));
    return candidates
        .map((c) => SchedulerImpl(maxSteps: maxSteps, choices: c))
        .toList();
  }

  @override
  String describeExample(Scheduler example) => example.toString();

  static List<int> _trimmed(List<int> choices) {
    var length = choices.length;
    while (length > 0 && choices[length - 1] == 0) {
      length--;
    }
    return choices.sublist(0, length);
  }
}

/// An object generated by `scheduler()` that runs asynchronous code
/// in an order of its own.
///
/// Dart runs asynchronous code on a single thread, and code running
/// concurrently interleaves only where it waits for a future.
/// A scheduler runs the microtasks created by the code, such as the
/// continuations after `await`, in an order chosen by kiri-check instead
/// of the order Dart itself uses, to find interleavings that break the code.
/// When a property fails, the order is shrunk towards the order Dart uses.
abstract class Scheduler {
  /// Runs [body] and returns its result.
  ///
  /// Each time two or more microtasks created by [body] are ready to run,
  /// the scheduler chooses which one runs next. Timers created by [body]
  /// run on virtual time: when no microtask is ready, the timer due first
  /// runs at once, in the order the timers were created if they are due
  /// at the same time.
  ///
  /// The returned future completes after [body] has completed and the
  /// microtasks left by it have run. Timers left by [body] are cancelled.
  /// An error not handled by [body], such as one thrown by a microtask
  /// [body] did not wait for, completes the returned future with the error.
  ///
  /// Each call follows the same schedule from the beginning.
  /// Code outside of Dart, such as I/O, is not controlled by the scheduler.
  Future<T> run<T>(FutureOr<T> Function() body);

  /// The virtual time elapsed in the current or last run.
  Duration get elapsed;
}

final class SchedulerImpl extends Scheduler {
  SchedulerImpl({required this.maxSteps, required this.choices, this.seed});

  final int maxSteps;

  // The choices to make. Where they run out, a random task is chosen if
  // [seed] is given, otherwise the oldest one.
  final List<int> choices;
  final int? seed;

  // The choices made in the current or last run.
  List<int> get trace => List.unmodifiable(_trace);
  final List<int> _trace = [];

  int get steps => _steps;
  int _steps = 0;

  @override
  Duration get elapsed => _now;
  Duration _now = Duration.zero;

  bool _running = false;
  final Queue<void Function()> _microtasks = Queue();
  final List<_VirtualTimer> _timers = [];
  int _timerSequence = 0;
  Completer<void>? _wake;
  RandomXorshift? _random;
  _Failure? _uncaught;

  @override
  Future<T> run<T>(FutureOr<T> Function() body) async {
    if (_running) {
      throw StateError('The scheduler is already running');
    }
    _running = true;
    _trace.clear();
    _steps = 0;
    _now = Duration.zero;
    _microtasks.clear();
    _timers.clear();
    _uncaught = null;
    _random = seed != null ? RandomXorshift(seed) : null;

    final zone = Zone.current.fork(
      specification: ZoneSpecification(
        scheduleMicrotask: _scheduleMicrotask,
        createTimer: _createTimer,
        createPeriodicTimer: _createPeriodicTimer,
        handleUncaughtError: _handleUncaughtError,
      ),
    );

    // An error does not leave the zone through a future, so the result
    // is carried as a value.
    Object? result;
    var completed = false;
    unawaited(
      zone.run(() async {
        try {
          return _Success(await body());
          // Any error of the body is passed to the caller.
          // ignore: avoid_catches_without_on_clauses
        } catch (e, s) {
          return _Failure(e, s);
        }
      }).then((value) {
        result = value;
        completed = true;
        _wakeUp();
      }),
    );

    try {
      while (_uncaught == null) {
        if (_microtasks.isNotEmpty) {
          _runMicrotask();
        } else if (completed) {
          break;
        } else if (_timers.isNotEmpty) {
          _runTimer();
        } else {
          // Waits for code outside of the zone, such as I/O.
          _wake = Completer();
          await _wake!.future;
          _wake = null;
        }
      }
    } finally {
      for (final timer in _timers) {
        timer._active = false;
      }
      _timers.clear();
      _microtasks.clear();
      _running = false;
    }

    final uncaught = _uncaught;
    if (uncaught != null) {
      Error.throwWithStackTrace(uncaught.error, uncaught.stackTrace);
    }
    final value = result;
    if (value is _Failure) {
      Error.throwWithStackTrace(value.error, value.stackTrace);
    }
    return (value! as _Success).value as T;
  }

  void _step() {
    _steps++;
    if (_steps > maxSteps) {
      throw StateError(
        'The scheduler ran more than $maxSteps tasks; '
        'the code may not terminate',
      );
    }
  }

  void _runMicrotask() {
    _step();
    final length = _microtasks.length;
    var index = 0;
    if (length > 1) {
      final position = _trace.length;
      if (position < choices.length) {
        index = choices[position] % length;
      } else if (_random != null) {
        index = _random!.nextInt(length);
      }
      _trace.add(index);
    }

    void Function() task;
    if (index == 0) {
      task = _microtasks.removeFirst();
    } else {
      final tasks = _microtasks.toList();
      task = tasks.removeAt(index);
      _microtasks
        ..clear()
        ..addAll(tasks);
    }
    task();
  }

  void _runTimer() {
    _step();
    var next = _timers.first;
    for (final timer in _timers) {
      if (timer._due < next._due ||
          (timer._due == next._due && timer._sequence < next._sequence)) {
        next = timer;
      }
    }
    if (_now < next._due) {
      _now = next._due;
    }
    if (next._periodic) {
      next
        .._due = _now + next._duration
        .._sequence = _timerSequence++;
    } else {
      _timers.remove(next);
      next._active = false;
    }
    next._tick++;
    next._callback(next);
  }

  void _wakeUp() {
    final wake = _wake;
    if (wake != null && !wake.isCompleted) {
      wake.complete();
    }
  }

  void _scheduleMicrotask(
    Zone self,
    ZoneDelegate parent,
    Zone zone,
    void Function() f,
  ) {
    if (!_running) {
      parent.scheduleMicrotask(zone, f);
      return;
    }
    _microtasks.add(zone.bindCallbackGuarded(f));
    _wakeUp();
  }

  Timer _createTimer(
    Zone self,
    ZoneDelegate parent,
    Zone zone,
    Duration duration,
    void Function() f,
  ) {
    if (!_running) {
      return parent.createTimer(zone, duration, f);
    }
    final callback = zone.bindCallbackGuarded(f);
    return _addTimer(duration, (_) => callback(), periodic: false);
  }

  Timer _createPeriodicTimer(
    Zone self,
    ZoneDelegate parent,
    Zone zone,
    Duration period,
    void Function(Timer) f,
  ) {
    if (!_running) {
      return parent.createPeriodicTimer(zone, period, f);
    }
    final callback = zone.bindUnaryCallbackGuarded(f);
    return _addTimer(period, callback, periodic: true);
  }

  _VirtualTimer _addTimer(
    Duration duration,
    void Function(Timer) callback, {
    required bool periodic,
  }) {
    final positive = duration.isNegative ? Duration.zero : duration;
    final timer = _VirtualTimer(
      this,
      positive,
      _now + positive,
      _timerSequence++,
      callback,
      periodic: periodic,
    );
    _timers.add(timer);
    _wakeUp();
    return timer;
  }

  void _handleUncaughtError(
    Zone self,
    ZoneDelegate parent,
    Zone zone,
    Object error,
    StackTrace stackTrace,
  ) {
    if (!_running) {
      parent.handleUncaughtError(zone, error, stackTrace);
      return;
    }
    _uncaught ??= _Failure(error, stackTrace);
  }

  @override
  // Equal schedulers make the same choices. The state of a run is not
  // compared, so that the shrinker can tell the same candidates.
  // ignore: avoid_equals_and_hash_code_on_mutable_classes
  bool operator ==(Object other) =>
      other is SchedulerImpl &&
      seed == other.seed &&
      maxSteps == other.maxSteps &&
      const ListEquality<int>().equals(choices, other.choices);

  @override
  // Hashes what == compares.
  // ignore: avoid_equals_and_hash_code_on_mutable_classes
  int get hashCode =>
      Object.hash(seed, maxSteps, const ListEquality<int>().hash(choices));

  @override
  String toString() {
    if (_steps == 0) {
      return seed != null
          ? 'Scheduler(seed: $seed)'
          : 'Scheduler(choices: $choices)';
    }
    return 'Scheduler(choices: ${SchedulerArbitrary._trimmed(_trace)}, '
        'steps: $_steps)';
  }
}

final class _VirtualTimer implements Timer {
  _VirtualTimer(
    this._scheduler,
    this._duration,
    this._due,
    this._sequence,
    this._callback, {
    required bool periodic,
  }) : _periodic = periodic;

  final SchedulerImpl _scheduler;
  final Duration _duration;
  final void Function(Timer) _callback;
  final bool _periodic;
  Duration _due;
  int _sequence;
  int _tick = 0;
  bool _active = true;

  @override
  bool get isActive => _active;

  @override
  int get tick => _tick;

  @override
  void cancel() {
    _active = false;
    _scheduler._timers.remove(this);
  }
}

final class _Success {
  const _Success(this.value);

  final Object? value;
}

final class _Failure {
  const _Failure(this.error, this.stackTrace);

  final Object error;
  final StackTrace stackTrace;
}
